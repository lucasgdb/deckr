import { createHash } from 'node:crypto';
import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';

/*
 * The service worker, served at /sw.js (scope: the whole site). Built once at build time, with the version of the
 * art baked in: a hash of every image under public/. Strategies:
 * - images (card art through /_next/image, arenas, chests, icons, screenshots): cache first, kept for good in a
 *   cache named after that hash. Changing any art changes the hash, so a new worker installs and drops the old cache;
 * - Next's built files (/_next/static: content-hashed names): cache first, so the app opens instantly and offline;
 * - pages: network first, falling back to the last copy of the page (or the home page) when offline;
 * - the API: never cached.
 * In `next dev` only images are cached, so hot reload keeps working.
 */
export const dynamic = 'force-static';

const publicDir = path.join(process.cwd(), 'public');
const imageDirs = ['cards', 'arenas', 'chests', 'icons', 'screenshots'];

function artVersion() {
   const hash = createHash('sha256');
   for (const dir of imageDirs) {
      let files: string[] = [];
      try {
         files = readdirSync(path.join(publicDir, dir)).sort();
      } catch {
         continue;
      }
      for (const file of files) {
         hash.update(`${dir}/${file}`);
         hash.update(readFileSync(path.join(publicDir, dir, file)));
      }
   }
   return hash.digest('hex').slice(0, 12);
}

const script = (version: string, dev: boolean) => `// Deckr service worker. Generated by src/app/sw.js/route.ts.
const IMAGES = 'deckr-images-${version}';
const STATIC = 'deckr-static';
const PAGES = 'deckr-pages';
const DEV = ${dev};
const STATIC_LIMIT = 300;

self.addEventListener('install', (event) => {
   self.skipWaiting();
   // The home page, saved up front: the installed app always opens, even offline on its first launch.
   if (!DEV) event.waitUntil(caches.open(PAGES).then((cache) => cache.add('/')).catch(() => {}));
});

self.addEventListener('activate', (event) => {
   event.waitUntil(
      (async () => {
         // Art changed (new version): the old images go. Other caches stay.
         for (const key of await caches.keys()) {
            if (key.startsWith('deckr-images-') && key !== IMAGES) await caches.delete(key);
            if (DEV && (key === STATIC || key === PAGES)) await caches.delete(key);
         }
         await self.clients.claim();
      })(),
   );
});

const isImage = (url) =>
   url.pathname === '/_next/image' ||
   /^\\/(cards|arenas|chests|icons|screenshots)\\//.test(url.pathname) ||
   url.pathname === '/icon.svg' ||
   url.pathname === '/apple-icon';

async function cacheFirst(cacheName, request, limit) {
   const cache = await caches.open(cacheName);
   const hit = await cache.match(request);
   if (hit) return hit;

   const response = await fetch(request);
   if (response.ok && response.type === 'basic') {
      await cache.put(request, response.clone());
      if (limit) {
         const keys = await cache.keys();
         for (const key of keys.slice(0, Math.max(0, keys.length - limit))) await cache.delete(key);
      }
   }
   return response;
}

async function networkFirst(request) {
   const cache = await caches.open(PAGES);
   try {
      const response = await fetch(request);
      if (response.ok && response.type === 'basic') await cache.put(request, response.clone());
      return response;
   } catch {
      const copy = (await cache.match(request, { ignoreSearch: true })) ?? (await cache.match('/', { ignoreSearch: true }));
      return copy ?? new Response('<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>Deckr</title><body style="background:#000;color:#fff;font-family:system-ui;padding:24px">Deckr: offline.', { headers: { 'content-type': 'text/html; charset=utf-8' } });
   }
}

self.addEventListener('fetch', (event) => {
   const { request } = event;
   if (request.method !== 'GET') return;

   const url = new URL(request.url);
   if (url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return;

   if (isImage(url)) {
      event.respondWith(cacheFirst(IMAGES, request));
      return;
   }
   if (DEV) return;
   if (url.pathname.startsWith('/_next/static/')) {
      event.respondWith(cacheFirst(STATIC, request, STATIC_LIMIT));
      return;
   }
   if (request.mode === 'navigate') event.respondWith(networkFirst(request));
});
`;

export function GET() {
   return new Response(script(artVersion(), process.env.NODE_ENV !== 'production'), {
      headers: {
         'content-type': 'text/javascript; charset=utf-8',
         // The browser checks for a new worker on every visit; the images it caches carry their own version.
         'cache-control': 'no-cache',
      },
   });
}
